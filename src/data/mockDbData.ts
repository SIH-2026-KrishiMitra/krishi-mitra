function makeBuyer(orgName: string, buyerType: BuyerJoin['buyer_profile'] extends { buyer_type: infer T } | null ? T : string, trustScore: number, completedDeals: number): BuyerJoin {
  return {
    full_name: orgName,
    avatar_url: null,
    buyer_profile: {
      org_name: orgName,
      buyer_type: buyerType as string,
      trust_score: trustScore,
      completed_deals: completedDeals,
      verified: true,
    },
  }
}

